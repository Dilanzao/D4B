export const normalizeCreatureText = (value = '') => String(value).normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLocaleLowerCase().replace(/\s+/g, ' ').trim();

export function getCreatureById(id) {
  return creatureCatalog.find(item => item.id === id) || null;
}

export function getCreatureName(creature, language = 'pt-BR') {
  if (!creature) return '';
  return creature.names?.[language]?.trim() || creature.canonicalName?.trim() || creature.names?.['pt-BR']?.trim() || 'Nome não disponível';
}

export function findCreatureMatch(value, type = '') {
  const wanted = normalizeCreatureText(value);
  if (!wanted) return null;
  return creatureCatalog.find(item => (!type || item.type === type) && [item.id, item.canonicalName, ...Object.values(item.names || {})].some(name => normalizeCreatureText(name) === wanted)) || null;
}

export function searchCreatures({ type, query = '', language = 'pt-BR', limit = 30 } = {}) {
  const wanted = normalizeCreatureText(query);
  return creatureCatalog
    .filter(item => !type || item.type === type)
    .filter(item => !wanted || [getCreatureName(item, language), item.canonicalName, ...Object.values(item.names || {})].some(name => normalizeCreatureText(name).includes(wanted)))
    .sort((a, b) => getCreatureName(a, language).localeCompare(getCreatureName(b, language), language))
    .slice(0, Math.max(1, limit));
}
